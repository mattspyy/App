const DICTIONARIES: Record<Language, Dictionary> = {
  "zh-HK": ZH_HK,
  en: EN,
  "zh-CN": ZH_CN,
};

export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string;

function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}

export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTIONARIES[lang] || DICTIONARIES[DEFAULT_LANGUAGE];
  const raw = dict[key] ?? DICTIONARIES[DEFAULT_LANGUAGE][key] ?? key;
  return format(raw, vars);
}

export function useLanguage(): { language: Language; t: TranslateFn; setLanguage: (l: Language) => void } {
  const raw = useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);
  const language: Language = isLanguage(raw) ? raw : DEFAULT_LANGUAGE;
  const t = useMemo<TranslateFn>(() => (key, vars) => translate(language, key, vars), [language]);
  return { language, t, setLanguage };
}

import type { ExpenseCategory, PaymentMethod, SplitType, SourceType } from "@/lib/types";

export function categoryLabel(category: ExpenseCategory | string, lang: Language): string {
  const key = `category.${category}`;
  const label = translate(lang, key);
  // Custom categories have no translation key — fall back to the raw name.
  return label === key ? String(category) : label;
}

export function paymentMethodLabel(method: PaymentMethod | string | undefined | null, lang: Language): string {
  if (!method) return translate(lang, "common.dash");
  return translate(lang, `paymentMethod.${method}`);
}

