export type Language = "zh-HK" | "en" | "zh-CN";

export const SUPPORTED_LANGUAGES: { code: Language; label: string }[] = [
  { code: "zh-HK", label: "繁體中文" },
  { code: "en", label: "English" },
  { code: "zh-CN", label: "简体中文" },
];

export const DEFAULT_LANGUAGE: Language = "zh-HK";

const STORAGE_KEY = "fxt.language";
const CHANGE_EVENT = "fxt.language.change";

function isLanguage(value: unknown): value is Language {
  return value === "zh-HK" || value === "en" || value === "zh-CN";
}

export function getLanguage(): Language {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    return isLanguage(raw) ? raw : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function setLanguage(lang: Language): void {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(STORAGE_KEY, lang);
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
  }
  window.dispatchEvent(new Event(CHANGE_EVENT));
}

function subscribe(cb: () => void): () => void {
  if (typeof window === "undefined") return () => {};
  window.addEventListener(CHANGE_EVENT, cb);
  window.addEventListener("storage", cb);
  return () => {
    window.removeEventListener(CHANGE_EVENT, cb);
    window.removeEventListener("storage", cb);
  };
}

function getSnapshot(): string {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  const raw = window.localStorage.getItem(STORAGE_KEY);
  return isLanguage(raw) ? raw : DEFAULT_LANGUAGE;
}

function getServerSnapshot(): string {
  return DEFAULT_LANGUAGE;
}

